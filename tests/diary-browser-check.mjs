import assert from 'node:assert/strict';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { mkdtemp, cp, mkdir, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { spawn } from 'node:child_process';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const project = fileURLToPath(new URL('../', import.meta.url));
const temp = await mkdtemp(path.join(tmpdir(), 'diary-browser-'));
let server, browser;
const port = Number(process.env.QA_DIARY_PORT || 4186);
if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error('Invalid test port');
try {
  await cp(path.join(project, 'scripts'), path.join(temp, 'scripts'), { recursive: true });
  await cp(path.join(project, 'dist'), path.join(temp, 'dist'), { recursive: true, filter: source => !source.includes(`${path.sep}vendor`) });
  await mkdir(path.join(temp, 'data', 'diary'), { recursive: true });
  server = spawn(process.execPath, [path.join(temp, 'scripts', 'serve.mjs')], { env: { ...process.env, PORT: String(port), PREVIEW_STATIC: '' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('exit', () => reject(new Error('Test server failed'))); });
  const base = `http://127.0.0.1:${port}`;
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const context = await browser.newContext({ viewport: { width: 1366, height: 1000 } });
  const page = await context.newPage(); const errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith(base)) external.push(r.url()); });
  await page.goto(base); assert.equal(await page.locator('.tool-card').count(), 4);
  await page.locator('[href="#/diary"]').click(); await page.locator('#diary-gate').waitFor({ state: 'visible' });
  assert.ok(await page.locator('#diary-search,#entry-title,#entry-body').evaluateAll(nodes => nodes.every(node => node.spellcheck === false && node.getAttribute('autocomplete') === 'off')));
  await page.locator('#diary-password').fill('synthetic-browser-password'); await page.locator('#diary-confirm').fill('synthetic-browser-password');
  await page.locator('#unlock-button').click(); await page.locator('#diary-workspace').waitFor({ state: 'visible' });
  await page.locator('#entry-date').fill('2026-10-11'); await page.locator('#entry-title').fill('<img src=x onerror=alert(1)>');
  await page.locator('#entry-body').fill('SYNTHETIC_BROWSER_MARKER'); await page.locator('#save-entry').click();
  await page.waitForFunction(() => document.querySelector('#diary-status').textContent.includes('저장했습니다'));
  assert.equal(await page.locator('.diary-list-item').count(), 1); assert.equal(await page.locator('#entry-list img').count(), 0);
  const disk = await readFile(path.join(temp, 'data', 'diary', 'vault.json'), 'utf8'); assert.ok(!disk.includes('SYNTHETIC_BROWSER_MARKER'));
  await mkdir(path.join(project, 'qa'), { recursive: true });
  await page.screenshot({ path: path.join(project, 'qa', 'diary-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(project, 'qa', 'diary-mobile.png'), fullPage: true });
  await page.reload(); await page.locator('#diary-gate').waitFor({ state: 'visible' });
  await page.locator('#diary-password').fill('wrong-synthetic-password'); await page.locator('#unlock-button').click();
  await page.waitForFunction(() => document.querySelector('#diary-status').textContent.includes('비밀번호가 다르'));
  await page.locator('#diary-password').fill('synthetic-browser-password'); await page.locator('#unlock-button').click(); await page.locator('#diary-workspace').waitFor({ state: 'visible' });
  await page.locator('.diary-list-item').click(); assert.equal(await page.locator('#entry-body').inputValue(), 'SYNTHETIC_BROWSER_MARKER');
  await page.locator('#diary-search').fill('absent'); assert.equal(await page.locator('.diary-list-item').count(), 0); await page.locator('#diary-search').fill('');
  await page.locator('#entry-body').fill('SYNTHETIC_EDIT');
  page.once('dialog', d => d.dismiss()); await page.locator('.back-link').click(); await page.waitForURL('**/#/diary');
  assert.equal(await page.locator('#entry-body').inputValue(), 'SYNTHETIC_EDIT');
  await page.locator('#save-entry').click(); await page.waitForFunction(() => document.querySelector('#diary-status').textContent.includes('저장했습니다'));
  page.once('dialog', d => d.accept()); await page.locator('#delete-entry').click(); await page.waitForFunction(() => document.querySelector('#diary-status').textContent.includes('삭제했습니다'));
  assert.equal(await page.locator('.diary-list-item').count(), 0);
  await page.locator('#lock-diary').click(); await page.locator('#diary-gate').waitFor({ state: 'visible' }); assert.equal(await page.locator('#entry-body').inputValue(), '');
  assert.equal((await fetch(`${base}/api/diary`)).status, 403);
  assert.equal((await fetch(`${base}/api/diary`, { headers: { 'X-Diary-Request': '1', Origin: 'https://example.invalid' } })).status, 403);
  assert.equal((await fetch(`${base}/data/diary/vault.json`)).status, 404);
  assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0, 0]);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('PASS: hub, create, encrypted disk, XSS, mobile, reload, wrong password, search, draft guard, edit, delete, lock, origin protections, no browser storage/external requests');
} finally {
  await browser?.close();
  if (server && server.exitCode === null) { server.kill(); await new Promise(resolve => server.once('exit', resolve)); }
  await rm(temp, { recursive: true, force: true });
}
